#!/usr/bin/env python3
"""Writes the NID name table of bbhle (src/hle/nid_table.hpp) from symbols/nids.csv.

Usage: gen_nid_table.py <nids.csv> <output.cpp>

The build runs it whenever the CSV or this script changes. The output is a C++ array sorted by
NID, one entry per NID: a NID is the hash of its name, so the rows of one NID in several
libraries carry the same name.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

FIELDS = ["nid", "library", "name", "source"]
NID_RE = re.compile(r"[A-Za-z0-9+-]{11}")
NAME_RE = re.compile(r"[!-~]+")  # printable ASCII without spaces, as tools/nidmatch writes


class TableError(Exception):
    pass


def read_names(path: Path) -> dict[str, str]:
    """NID -> name from nids.csv, after checking the columns, the NIDs and the names."""
    names: dict[str, str] = {}
    with path.open(newline="") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != FIELDS:
            raise TableError(f"{path}: expected columns {','.join(FIELDS)}")
        for lineno, row in enumerate(reader, 2):
            # DictReader fills a short row with None values and puts the rest of a long row under
            # None.
            if None in row or None in row.values():
                raise TableError(f"{path}:{lineno}: wrong number of fields")
            nid, name = row["nid"], row["name"]
            if not NID_RE.fullmatch(nid) or not NAME_RE.fullmatch(name):
                raise TableError(f"{path}:{lineno}: bad NID or name")
            if names.setdefault(nid, name) != name:
                raise TableError(f"{path}:{lineno}: {nid} has the names {names[nid]} and {name}")
    return names


def cpp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(names: dict[str, str]) -> str:
    rows = "".join(f"    {{{cpp_string(nid)}, {cpp_string(names[nid])}}},\n"
                   for nid in sorted(names))
    return ("// Generated by tools/nidtable/gen_nid_table.py from symbols/nids.csv. Do not edit.\n"
            '#include "hle/nid_table.hpp"\n\n'
            "#include <array>\n\n"
            "namespace bb::hle {\n"
            "namespace {\n"
            f"constexpr std::array<NidName, {len(names)}> table = {{{{\n"
            f"{rows}"
            "}};\n"
            "static_assert(is_sorted_by_nid(table));\n"
            "}  // namespace\n\n"
            "std::span<const NidName> nid_table() {\n"
            "    return table;\n"
            "}\n\n"
            "}  // namespace bb::hle\n")


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__.splitlines()[2], file=sys.stderr)
        return 2
    try:
        text = render(read_names(Path(argv[1])))
    except (OSError, UnicodeError, TableError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    Path(argv[2]).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
